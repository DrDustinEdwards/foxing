// The security header set, in a module that imports only packages so scripts/gen-headers.mjs can load it with Node's
// type stripping. Foxing's deviations and their reasons are its entry in site-runtime's site registry (./sites,
// `foxing`); Prelum's TDMRep header goes beside it, reserving training rights as /ai.txt says.
import { TDM_RESERVATION_HEADERS } from "@drdustinedwards/site-helpers/robots";
import { buildSecurityHeaders, corpFor, headersFile } from "@dustinedwards/site-runtime/headers";
import { foxing } from "@dustinedwards/site-runtime/sites";

export const securityHeaders: Readonly<Record<string, string>> = Object.freeze({
  ...buildSecurityHeaders({ site: foxing }),
  ...TDM_RESERVATION_HEADERS,
});

/**
 * public/_headers, which `pnpm build` writes: static files are served without the Worker, so they carry the same set.
 * Built files are named by their content hash, so a year is safe for /assets/*; files at stable paths keep the
 * default revalidation. Scripts, styles, fonts and images may be loaded by other origins (site-runtime's corpFor).
 */
export function staticHeadersFile(): string {
  const types: Record<string, string> = {
    svg: "image/svg+xml",
    css: "text/css",
    js: "text/javascript",
    woff2: "font/woff2",
  };
  return headersFile(securityHeaders, {
    comment: "GENERATED by scripts/gen-headers.mjs from workers/header-set.ts, on every build.",
    charset: true,
    paths: {
      ...Object.fromEntries(
        Object.entries(types).map(([ext, type]) => [
          `/*.${ext}`,
          { "Cross-Origin-Resource-Policy": corpFor(type) },
        ]),
      ),
      "/assets/*": { "Cache-Control": "public, max-age=31536000, immutable" },
    },
  });
}
